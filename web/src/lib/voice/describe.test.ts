describe('parseYesNo', () => {
  it.each([
    'ναι', 'Ναι.', 'ναι ναι', 'ΝΑΙ', 'εντάξει', 'οκ', 'ok', 'OK!', 'σωστό', 'πέρασέ το', 'καταχώρησε', 'μάλιστα',
    'βεβαίως', 'yes', 'ναι, πέρασέ το', 'ναι σωστό', 'ε ναι',
  ])('%s → yes', (t) => {
    expect(parseYesNo(t)).toBe('yes')
  })
  it.each(['όχι', 'Όχι!', 'άκυρο', 'ακύρωσε', 'λάθος', 'σταμάτα', 'no', 'όχι όχι', 'μην το περάσεις', 'άσ\' το'])('%s → no', (t) => {
    expect(parseYesNo(t)).toBe('no')
  })
  it.each(['', 'ίσως', 'δεν ξέρω', 'ναι όχι', 'efood δύο μαργαρίτες', 'μπορεί'])('%s → null', (t) => {
    expect(parseYesNo(t)).toBeNull()
  })
  it.each([
    'δεν είναι σωστό', 'δεν είναι εντάξει', 'καθόλου σωστό', 'δεν είναι σωστά', 'μη το περάσεις', 'δεν θέλω', 'όχι ακόμα',
    'περίμενε λίγο', 'όχι ευχαριστώ', 'δεν το θέλω, ακύρωσε', 'όχι λάθος', 'όχι δεν είναι', 'μη', 'Μην!',
  ])('άρνηση: %s → no', (t) => {
    expect(parseYesNo(t)).toBe('no')
  })
  it.each([
    // νέα εντολή ή διόρθωση: δεν επιβεβαιώνει την κάρτα που περιμένει
    'πέρασε 3 μαργαρίτες στο efood', 'καταχώρησε δύο σπέσιαλ', 'ok efood 2 μαργαρίτες', 'εντάξει, βάλε και δύο σπέσιαλ',
    'ναι αλλά βάλε τρεις', 'ναι τρεις μαργαρίτες', 'λάθος, τρεις μαργαρίτες', 'όχι, πέρασέ το', 'όχι σωστό', 'Δεν', 'σιγά',
  ])('περιεχόμενο / ανάμεικτα: %s → null', (t) => {
    expect(parseYesNo(t)).toBeNull()
  })
  it.each(['σωστό ναι', 'ναι ναι ναι', 'ναι ρε', 'τέλεια, ναι', 'καταχώρησέ το', 'είναι σωστό'])('%s → yes', (t) => {
    expect(parseYesNo(t)).toBe('yes')
  })
  it('δεν σκάει', () => {
    expect(parseYesNo(undefined as unknown as string)).toBeNull()
  })
})
