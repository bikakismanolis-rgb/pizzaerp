describe('parseYesNo', () => {
  it.each([
    'ναι', 'Ναι.', 'ναι ναι', 'ΝΑΙ', 'εντάξει', 'οκ', 'ok', 'OK!', 'σωστό', 'πέρασέ το', 'καταχώρησε', 'μάλιστα',
    'βεβαίως', 'yes', 'ναι, πέρασέ το', 'ναι σωστό', 'ε ναι',
  ])('%s → yes', (t) => {
    expect(parseYesNo(t)).toBe('yes')
  })
  it.each(['όχι', 'Όχι!', 'άκυρο', 'ακύρωσε', 'λάθος', 'σταμάτα', 'no', 'όχι όχι', 'μην το περάσεις', 'άσ\' το'])('%s → no', (t) => {
    expect(parseYesNo(t)).toBe('no')
  })
  it.each(['', 'ίσως', 'δεν ξέρω', 'ναι όχι', 'efood δύο μαργαρίτες', 'μπορεί'])('%s → null', (t) => {
    expect(parseYesNo(t)).toBeNull()
  })
  it('δεν σκάει', () => {
    expect(parseYesNo(undefined as unknown as string)).toBeNull()
  })
})
