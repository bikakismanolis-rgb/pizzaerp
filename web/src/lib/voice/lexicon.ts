/** Γενική λέξη συσκευασίας → κανονική μορφή ("σακιά" → "σακί") */
export function genericPack(n: string): string | null {
  return PACK_FORM.get(n) ?? null
}

const formsCache = new Map<string, Set<string>>()

/** Πιθανοί τύποι (κλίσεις) ενός ονόματος συσκευασίας */
export function packForms(packName: string): Set<string> {
  const hit = formsCache.get(packName)
  if (hit) return hit
  const out = buildPackForms(packName)
  if (formsCache.size < 500) formsCache.set(packName, out)
  return out
}

function buildPackForms(packName: string): Set<string> {
  const p = norm(String(packName ?? '')).trim()
  const out = new Set<string>()
  if (!p) return out
  out.add(p)
  const canon = genericPack(p)
  if (canon) for (const [f, c] of PACK_FORM) if (c === canon) out.add(f)
  const add = (s: string) => out.add(s)
  if (p.endsWith('ι')) { add(p + 'α'); add(p + 'ου'); add(p + 'ων') }
  else if (p.endsWith('ο')) { add(p.slice(0, -1) + 'α'); add(p.slice(0, -1) + 'ου'); add(p.slice(0, -1) + 'ων') }
  else if (p.endsWith('α')) { add(p + 'σ'); add(p.slice(0, -1) + 'εσ'); add(p.slice(0, -1) + 'ων') }
  else if (p.endsWith('η')) { add(p + 'σ'); add(p.slice(0, -1) + 'εσ') }
  else if (p.endsWith('εσ')) { add(p.slice(0, -2) + 'εδεσ'); add(p.slice(0, -1)) }
  return out
}

/** Η λέξη είναι η συσκευασία του είδους; */
export function isItemPack(n: string, item: Item | null | undefined): boolean {
  if (!item?.pack_name) return false
  return packForms(item.pack_name).has(n)
}

