export type MeasureUnit = 'kg' | 'g' | 'L' | 'ml' | 'τεμ'
/** και μονάδες που εμφανίζονται μόνο μέσα σε ονόματα (Special 30εκ) */
export type NameUnit = MeasureUnit | 'εκ'

const UNIT_WORDS: Record<string, NameUnit> = {}
const addUnit = (u: NameUnit, words: string) => words.split(' ').forEach((w) => { UNIT_WORDS[w] = u })
addUnit('kg', 'κιλο κιλα κιλου κιλων κιλακι κιλακια kg kgs kilo kila kilos kgr κγρ χιλιογραμμο χιλιογραμμα χιλιογραμμων')
addUnit('g', 'γραμμαριο γραμμαρια γραμμαριων γραμμαριου γραμ γρ γραμμ γραμματα g gr grams gram γκρ')
addUnit('L', 'λιτρο λιτρα λιτρου λιτρων λιτρακι λιτ λτ l lt ltr litre liter litres liters λιτρο')
addUnit('ml', 'ml μλ μιλιλιτρ μιλιλιτρα μιλιλιτρο μιλιλιτρων')
addUnit('τεμ', 'τεμαχιο τεμαχια τεμαχιων τεμαχιου τεμ τμχ κομματι κομματια κομματιων τεμαχ pcs τεμαχιακια')
addUnit('εκ', 'εκ εκατοστα εκατοστων εκατοστο εκατοστου cm')

export function unitWord(n: string): NameUnit | null {
  return UNIT_WORDS[n] ?? null
}

const UNIT_INFO: Record<MeasureUnit, { dim: string; f: number }> = {
  kg: { dim: 'mass', f: 1000 },
  g: { dim: 'mass', f: 1 },
  L: { dim: 'vol', f: 1000 },
  ml: { dim: 'vol', f: 1 },
  τεμ: { dim: 'count', f: 1 },
}

export function isMeasureUnit(u: string): u is MeasureUnit {
  return u in UNIT_INFO
}

/** Μετατροπή v από μονάδα σε μονάδα (null αν είναι διαφορετικού είδους) */
export function convertUnit(v: number, from: MeasureUnit, to: string): number | null {
  if (from === to) return v
  if (!isMeasureUnit(to)) return null
  const a = UNIT_INFO[from]
  const b = UNIT_INFO[to]
  if (a.dim !== b.dim) return null
  return Math.round(((v * a.f) / b.f) * 1e6) / 1e6
}

