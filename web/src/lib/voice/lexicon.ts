/** Κανάλι που ξεκινά στο token i ("efood", "e food", "ιφούντ", "βολτ", "μποξ", "τηλέφωνο", "μαγαζί", "από μέσα") */
export function channelAt(toks: Tok[], i: number): { ch: TallyChannel; len: number } | null {
  const t = toks[i]
  if (!t || t.sep || t.num !== undefined) return null
  const n = t.n
  const p = phon(n)
  const next = toks[i + 1]
  const np = next && !next.sep && next.num === undefined ? phon(next.n) : ''
  if ((p === 'e' || p === 'i') && /^fu[dt]s?$/.test(np)) return { ch: 'efood', len: 2 }
  if (/^[ei]?fu[dt]s?$/.test(p)) return { ch: 'efood', len: 1 }
  if (/^(volt|vold|guolt|uolt|vuolt|volts)$/.test(p)) return { ch: 'wolt', len: 1 }
  if (/^(boks|box|bokz)$/.test(p)) return { ch: 'box', len: 1 }
  if (/^τηλεφων/.test(n) || n === 'τηλ' || n === 'phone') return { ch: 'phone', len: 1 }
  if (STORE_WORDS.has(n)) return { ch: 'store', len: 1 }
  if (n === 'απο' && next?.n === 'μεσα') return { ch: 'store', len: 2 }
  return null
}

