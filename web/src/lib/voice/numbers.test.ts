import { describe, expect, it } from 'vitest'
import { tokenize } from './normalize'
import { cardinal, numbersIn, segment, type NumSeg } from './numbers'

const nums = (s: string) => numbersIn(tokenize(s))
const firstNum = (s: string) => segment(tokenize(s)).find((x): x is NumSeg => x.t === 'n')

describe('αριθμοί με λέξεις', () => {
  it.each([
    ['μηδέν', 0],
    ['ένα', 1],
    ['μία', 1],
    ['μια', 1],
    ['δύο', 2],
    ['δυο', 2],
    ['τρεις', 3],
    ['τρία', 3],
    ['τέσσερις', 4],
    ['έξι', 6],
    ['εφτά', 7],
    ['επτά', 7],
    ['οχτώ', 8],
    ['εννιά', 9],
    ['δέκα', 10],
    ['έντεκα', 11],
    ['δεκαπέντε', 15],
    ['δεκαεφτά', 17],
    ['είκοσι', 20],
    ['είκοσι τρία', 23],
    ['σαράντα επτά', 47],
    ['εξήντα', 60],
    ['ογδόντα', 80],
    ['ενενήντα εννιά', 99],
    ['εκατό', 100],
    ['εκατόν πενήντα', 150],
    ['εκατόν είκοσι', 120],
    ['διακόσια πενήντα', 250],
    ['τριακόσιες', 300],
    ['τετρακόσια', 400],
    ['εννιακόσια ενενήντα εννιά', 999],
    ['χίλια', 1000],
    ['χίλια διακόσια πενήντα', 1250],
    ['δύο χιλιάδες', 2000],
    ['δύο χιλιάδες πεντακόσια', 2500],
    ['τρεις χιλιάδες διακόσια', 3200],
    ['εικοσιπέντε', 25],
    ['τριανταδύο', 32],
    ['εκατόν εικοσιπέντε', 125],
  ])('%s = %d', (s, v) => {
    expect(nums(s)).toEqual([v])
  })
})

describe('κλάσματα και δεκαδικά', () => {
  it.each([
    ['μισό', 0.5],
    ['μισή', 0.5],
    ['ενάμισι', 1.5],
    ['ενάμιση', 1.5],
    ['μιάμιση', 1.5],
    ['δυόμισι', 2.5],
    ['τρεισήμισι', 3.5],
    ['πεντέμισι', 5.5],
    ['δύο και μισό', 2.5],
    ['έξι κόμμα πέντε', 6.5],
    ['μηδέν κόμμα εξήντα δύο', 0.62],
    ['ένα κόμμα είκοσι πέντε', 1.25],
    ['μηδέν κόμμα μηδέν πέντε', 0.05],
    ['6 κόμμα 5', 6.5],
    ['6,5', 6.5],
    ['0.62', 0.62],
  ])('%s = %d', (s, v) => {
    expect(nums(s)).toEqual([v])
  })
})

describe('ακολουθίες', () => {
  it('οι μονάδες δεν ενώνονται μεταξύ τους (ψηφία τηλεφώνου)', () => {
    expect(nums('δύο οκτώ ένα μηδέν')).toEqual([2, 8, 1, 0])
    expect(nums('2810 123 456')).toEqual([2810, 123, 456])
  })
  it('δύο αριθμοί για δύο είδη', () => {
    expect(nums('τρεις μαργαρίτες και δύο σπέσιαλ')).toEqual([3, 2])
    expect(nums('σαράντα επτά κιλά και είκοσι τρία ζυμάρια')).toEqual([47, 23])
  })
  it('"τέσσερα και πενήντα" μένουν δύο αριθμοί (η τιμή ενώνεται αργότερα)', () => {
    expect(nums('τέσσερα και πενήντα')).toEqual([4, 50])
  })
  it('ψηφία + "χιλιάδες"', () => {
    expect(nums('2 χιλιάδες')).toEqual([2000])
  })
  it('χιλιάδες + υπόλοιπο, μισά, ψηφία μαζί με λέξεις', () => {
    expect(nums('2 χιλιάδες 500')).toEqual([2500])
    expect(nums('δύο χιλιάδες 500')).toEqual([2500])
    expect(nums('χίλια 500')).toEqual([1500])
    expect(nums('δυόμισι χιλιάδες')).toEqual([2500])
    expect(nums('2,5 χιλιάδες')).toEqual([2500])
    expect(nums('ενάμισι κιλό')).toEqual([1.5])
    expect(nums('2 χιλιάδες 0030')).toEqual([2000, 30])
  })
})

describe('σημαίες', () => {
  it('μέγεθος (τετρακοσάρι, 400άρια)', () => {
    expect(firstNum('τετρακοσάρια')).toMatchObject({ value: 400, size: true })
    expect(firstNum('διακοσαπενηντάρι')).toMatchObject({ value: 250, size: true })
    expect(firstNum('400άρια')).toMatchObject({ value: 400, size: true })
  })
  it('ποσοστό', () => {
    expect(firstNum('24%')).toMatchObject({ value: 24, pct: true })
    expect(firstNum('24 τοις εκατό')).toMatchObject({ value: 24, pct: true })
  })
  it('μισό', () => {
    expect(firstNum('μισό κιλό')).toMatchObject({ value: 0.5, half: true })
  })
  it('ψηφία για συνένωση', () => {
    expect(firstNum('0030')?.digits).toBe('0030')
  })
  it('cardinal: slots', () => {
    expect(cardinal('εικοσι')).toEqual({ v: 20, slot: 1 })
    expect(cardinal('πεντακοσιεσ')).toEqual({ v: 500, slot: 2 })
    expect(cardinal('μαργαριτα')).toBeNull()
  })
  it('λέξεις που δεν είναι αριθμοί', () => {
    expect(nums('μαργαρίτα σπέσιαλ εκατοστά')).toEqual([])
  })
})
