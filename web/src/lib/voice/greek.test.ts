import { describe, expect, it } from 'vitest'
import { countName, pluralName } from './greek'

describe('pluralName: πληθυντικός ονομάτων ειδών', () => {
  it.each([
    ['Μαργαρίτα', 'Μαργαρίτες'],
    ['Χαβανέζα', 'Χαβανέζες'],
    ['Πίτσα', 'Πίτσες'],
    ['Ζυμάρι', 'Ζυμάρια'],
    ['Ζυμάρι 250γρ', 'Ζυμάρια 250γρ'],
    ['Κουτί πίτσας', 'Κουτιά πίτσας'],
    ['Κουτί', 'Κουτιά'],
    ['Σαλάτα εποχής', 'Σαλάτες εποχής'],
    ['Πίτσα του σεφ', 'Πίτσες του σεφ'],
    ['Σουβλάκι', 'Σουβλάκια'],
    ['Παγωτό', 'Παγωτά'],
    ['Κοτόπουλο', 'Κοτόπουλα'],
    ['Γύρος', 'Γύροι'],
    ['Μαργαρίτα σκέτη', 'Μαργαρίτες σκέτες'],
    ['Μεγάλη Μαργαρίτα', 'Μεγάλες Μαργαρίτες'],
    ['Μικρή πίτσα', 'Μικρές πίτσες'],
    ['Πίτσα με μανιτάρια', 'Πίτσες με μανιτάρια'],
    ['Πίτσα χωρίς τυρί', 'Πίτσες χωρίς τυρί'],
    // ξένα: δεν κλίνονται
    ['Special', 'Special'],
    ['Coca-Cola 330ml', 'Coca-Cola 330ml'],
    ['Special κατεψυγμένη 30εκ', 'Special κατεψυγμένες 30εκ'],
    ['Σπέσιαλ', 'Σπέσιαλ'],
    ['Καλτσόνε', 'Καλτσόνε'],
    ['Τοστ', 'Τοστ'],
    // ήδη πληθυντικός
    ['Πατάτες', 'Πατάτες'],
    ['Παϊδάκια', 'Παϊδάκια'],
    // χωρίς ασφαλή κανόνα: όπως ήταν
    ['Κρέμα', 'Κρέμα'],
    ['Μουσακάς', 'Μουσακάς'],
  ])('%s → %s', (one, many) => {
    expect(pluralName(one)).toBe(many)
  })

  it('ένα: ενικός, αλλιώς πληθυντικός', () => {
    expect(countName(1, 'Μαργαρίτα')).toBe('Μαργαρίτα')
    expect(countName(-1, 'Μαργαρίτα')).toBe('Μαργαρίτα')
    expect(countName(3, 'Μαργαρίτα')).toBe('Μαργαρίτες')
    expect(countName(0.5, 'Μαργαρίτα')).toBe('Μαργαρίτες')
  })
})
